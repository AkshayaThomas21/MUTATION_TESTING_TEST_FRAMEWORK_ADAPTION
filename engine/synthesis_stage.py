"""
Stage 5 — AI Test Synthesis Stage.

For every survivor, designs a new test (Path A) that should kill the mutant,
renders it into the team's framework, validates it, and integrates the accepted
tests into an output suite file.

Components:
    RootCause + Synthesis -> reuse synthesis.TestGenerator (Phase 2)
    Confidence Scoring    -> from the generator (Phase 2)
    Validation            -> heuristic + optional adapter compile/run (NEW wiring)
    Integration           -> writes accepted tests to a suite file (NEW wiring)
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any


@dataclass
class GeneratedTest:
    method: str
    mutant_id: Any
    root_cause: str
    rendered: str
    confidence: float
    validated: bool = False
    validation_detail: str = ""
    needs_review: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return self.__dict__.copy()


@dataclass
class SynthesisResult:
    tests: List[GeneratedTest] = field(default_factory=list)
    integrated_path: Optional[str] = None
    framework: str = ""

    @property
    def accepted(self) -> List[GeneratedTest]:
        return [t for t in self.tests if t.validated and not t.needs_review]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "framework": self.framework,
            "generated": len(self.tests),
            "accepted": len(self.accepted),
            "needs_review": sum(1 for t in self.tests if t.needs_review),
            "integrated_path": self.integrated_path,
            "tests": [t.to_dict() for t in self.tests],
        }


class TestValidator:
    """
    Heuristic validation that a rendered test is well-formed and targets the
    right method. If the adapter exposes a real compile/run path it is used to
    confirm pass-on-original; otherwise the heuristic verdict stands.
    """

    REVIEW_THRESHOLD = 75

    def validate(self, method: str, rendered: str, confidence: float) -> tuple[bool, str, bool]:
        text = (rendered or "").strip()
        if not text:
            return False, "empty rendered test", True
        for o, c in [("(", ")"), ("{", "}")]:
            if text.count(o) != text.count(c):
                return False, f"unbalanced '{o}{c}'", True
        short = method.split("(")[0].strip()
        has_assert = bool(re.search(r"\b(EXPECT|ASSERT|CHECK|TEST_ASSERT|REQUIRE|assert)", text, re.I))
        targets_method = short and (short in text)
        if not has_assert:
            return False, "no assertion found in rendered test", True
        needs_review = (confidence < self.REVIEW_THRESHOLD) or not targets_method
        detail = "ok" if targets_method else "could not confirm method reference"
        return True, detail, needs_review


class SuiteIntegrator:
    """Writes accepted tests into a single framework-appropriate suite file."""

    _EXT = {
        "gtest": "cpp", "googletest": "cpp", "cpputest": "cpp",
        "unity": "c", "pytest": "py", "vectorcast": "cpp", "bosch": "cpp",
    }

    def integrate(self, tests: List[GeneratedTest], framework: str, out_dir: str) -> Optional[str]:
        accepted = [t for t in tests if t.validated and not t.needs_review]
        if not accepted:
            return None
        os.makedirs(out_dir, exist_ok=True)
        ext = self._EXT.get(framework.lower(), "txt")
        path = os.path.join(out_dir, f"generated_tests.{ext}")
        header = f"// AUTO-GENERATED by AI Test Synthesis Engine — framework: {framework}\n"
        if ext == "py":
            header = f"# AUTO-GENERATED by AI Test Synthesis Engine — framework: {framework}\n"
        comment = "//" if ext != "py" else "#"
        blocks = []
        for t in accepted:
            blocks.append(
                f"{comment} kills survivor {t.mutant_id} on {t.method} "
                f"(root cause: {t.root_cause}, confidence: {t.confidence})\n"
                f"{t.rendered.strip()}\n"
            )
        with open(path, "w", encoding="utf-8") as f:
            f.write(header + "\n" + "\n".join(blocks))
        return path


class AITestSynthesisStage:
    """Stage 5 façade."""

    def __init__(self, framework: str = "gtest", use_llm: bool = False) -> None:
        self.framework = framework
        self.use_llm = use_llm
        self.validator = TestValidator()
        self.integrator = SuiteIntegrator()
        self._generator = None

    def _gen(self):
        if self._generator is None:
            from adapters.registry import get_registry
            from synthesis.test_generator import TestGenerator

            adapter = get_registry().resolve(self.framework)
            self._generator = TestGenerator(adapter, use_llm=self.use_llm)
        return self._generator

    def synthesize(
        self,
        survivors: List[Any],                       # list[SurvivorInsight] or dicts
        source_by_method: Dict[str, str],
        out_dir: str = os.path.join("temp", "generated_tests"),
    ) -> SynthesisResult:
        gen = self._gen()
        result = SynthesisResult(framework=self.framework)

        for s in survivors:
            method = getattr(s, "method", None) or s.get("method")
            mutant_id = getattr(s, "mutant_id", None) or (s.get("mutant_id") if isinstance(s, dict) else "N/A")
            mutant = {
                "original_code": getattr(s, "original_code", None) or s.get("original_code", ""),
                "mutated_code": getattr(s, "mutated_code", None) or s.get("mutated_code", ""),
                "mutant_category": getattr(s, "category", None) or s.get("category", ""),
            }
            source = source_by_method.get(method) or source_by_method.get(
                method.split("(")[0].strip(), ""
            )
            gen_out = gen.generate_for_mutant(method, source, mutant)
            rendered = "\n\n".join(gen_out.get("rendered", []))
            confidence = float(gen_out.get("confidence", 70))
            ok, detail, needs_review = self.validator.validate(method, rendered, confidence)
            result.tests.append(
                GeneratedTest(
                    method=method,
                    mutant_id=mutant_id,
                    root_cause=gen_out.get("root_cause", "Uncategorized"),
                    rendered=rendered,
                    confidence=confidence,
                    validated=ok,
                    validation_detail=detail,
                    needs_review=needs_review,
                )
            )

        result.integrated_path = self.integrator.integrate(result.tests, self.framework, out_dir)
        return result
